"""Export helpers: incident report (Markdown + minimal HTML) and a blocklist.

Nothing here executes anything. The blocklist is plain text an admin copies into
their own firewall after reviewing it.
"""

import html
from datetime import datetime

from .mitre import lookup


def _fmt_ts(iso):
    if not iso:
        return "-"
    try:
        return datetime.fromisoformat(iso).strftime("%Y-%m-%d %H:%M:%S")
    except ValueError:
        return iso


def incident_markdown(incident, alerts_by_id):
    L = []
    L.append("# Incident %s - %s" % (incident["id"], incident["src"] or "n/a"))
    L.append("")
    L.append("- **Severity:** %s" % incident["severity"].upper())
    L.append("- **Source IP:** %s" % (incident["src"] or "n/a"))
    L.append("- **Window:** %s -> %s" % (_fmt_ts(incident["start"]), _fmt_ts(incident["end"])))
    L.append("- **Alerts:** %d  |  **Categories:** %s"
             % (incident["alert_count"], ", ".join(incident["categories"])))
    L.append("- **Kill-chain:** %s" % " -> ".join(incident["phases"]))
    mitre = ", ".join("%s (%s)" % (m["id"], m["name"]) for m in incident["mitre"])
    L.append("- **MITRE ATT&CK:** %s" % mitre)
    L.append("")
    L.append("## Timeline")
    L.append("")
    L.append("| Time | Phase | Severity | Finding |")
    L.append("|------|-------|----------|---------|")
    for t in incident["timeline"]:
        L.append("| %s | %s | %s | %s |" % (
            _fmt_ts(t["ts"]), t["phase"], t["severity"].upper(), t["title"]))
    L.append("")
    L.append("## Alerts & recommended response")
    for aid in incident["alert_ids"]:
        a = alerts_by_id.get(aid)
        if not a:
            continue
        d = a.to_dict()
        L.append("")
        L.append("### %s - %s (%s)" % (d["id"], d["title"], d["severity"].upper()))
        L.append("")
        L.append(d["detail"])
        L.append("")
        L.append("**MITRE:** " + ", ".join("%s %s" % (m["id"], m["name"]) for m in d["mitre"]))
        L.append("")
        L.append("**Evidence (showing %d of %d):**" % (len(d["evidence"]), d["evidence_count"]))
        L.append("")
        L.append("```")
        L.extend(d["evidence"])
        L.append("```")
        L.append("")
        L.append("**Recommended response:**")
        for r in d["response"]:
            L.append("- " + r)
    L.append("")
    L.append("_Generated by LogSentinel. Review before acting; this report performs no changes._")
    return "\n".join(L)


def incident_html(incident, alerts_by_id):
    md = incident_markdown(incident, alerts_by_id)
    # Minimal, dependency-free MD->HTML (headings, tables, code, lists, bold).
    out = ["<!doctype html><html><head><meta charset='utf-8'>",
           "<title>%s</title>" % html.escape(incident["id"]),
           "<style>body{font:15px/1.5 system-ui,sans-serif;max-width:860px;",
           "margin:40px auto;padding:0 20px;color:#0b0f14}h1,h2,h3{color:#166534}",
           "table{border-collapse:collapse;width:100%}td,th{border:1px solid #cbd5e1;",
           "padding:6px 10px;text-align:left}pre{background:#0b0f14;color:#22c55e;",
           "padding:12px;border-radius:8px;overflow:auto;font-size:12px}",
           "code{font-family:ui-monospace,monospace}</style></head><body>"]
    in_code = in_table = False
    in_list = False
    for line in md.split("\n"):
        if line.startswith("```"):
            if in_code:
                out.append("</pre>")
                in_code = False
            else:
                out.append("<pre>")
                in_code = True
            continue
        if in_code:
            out.append(html.escape(line))
            continue
        if line.startswith("| "):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if set("".join(cells)) <= set("-| "):
                continue
            if not in_table:
                out.append("<table>")
                in_table = True
                out.append("<tr>" + "".join("<th>%s</th>" % html.escape(c) for c in cells) + "</tr>")
            else:
                out.append("<tr>" + "".join("<td>%s</td>" % html.escape(c) for c in cells) + "</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if line.startswith("### "):
            out.append("<h3>%s</h3>" % html.escape(line[4:]))
        elif line.startswith("## "):
            out.append("<h2>%s</h2>" % html.escape(line[3:]))
        elif line.startswith("# "):
            out.append("<h1>%s</h1>" % html.escape(line[2:]))
        elif line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append("<li>%s</li>" % _inline(line[2:]))
        elif line.strip() == "":
            if in_list:
                out.append("</ul>")
                in_list = False
        else:
            if in_list:
                out.append("</ul>")
                in_list = False
            out.append("<p>%s</p>" % _inline(line))
    if in_table:
        out.append("</table>")
    if in_list:
        out.append("</ul>")
    out.append("</body></html>")
    return "\n".join(out)


def _inline(s):
    s = html.escape(s)
    while "**" in s:
        s = s.replace("**", "<b>", 1)
        if "**" in s:
            s = s.replace("**", "</b>", 1)
    return s


def blocklist_text(rows):
    L = ["# LogSentinel generated blocklist - REVIEW before applying.",
         "# This file is text only; LogSentinel never changes your firewall.",
         "# Generated %s" % datetime.now().strftime("%Y-%m-%d %H:%M"),
         ""]
    L.append("# ---- iptables ----")
    for r in rows:
        L.append("iptables -A INPUT -s %s -j DROP   # %s: %s"
                 % (r["ip"], r["severity"], ", ".join(r["reasons"])))
    L.append("")
    L.append("# ---- fail2ban (manual ban) ----")
    for r in rows:
        L.append("fail2ban-client set sshd banip %s" % r["ip"])
    L.append("")
    L.append("# ---- hosts.deny ----")
    for r in rows:
        L.append("ALL: %s" % r["ip"])
    return "\n".join(L) + "\n"
