"""Regenerate docs/PORTFOLIO.md from every projects/*/pitch.json.

    python tools/build_portfolio.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

DOMAIN_ORDER = [
    "Artificial Intelligence & Machine Learning",
    "Sustainability, CleanTech & Green Energy",
    "HealthTech & Biomedical Innovation",
    "Cybersecurity & Blockchain Technology",
    "Smart Agriculture & Rural Development (AgriTech)",
    "Data Science & Analytics",
]


def load():
    pitches = []
    for f in sorted((ROOT / "projects").glob("*/pitch.json")):
        p = json.loads(f.read_text(encoding="utf-8"))
        p["_dir"] = f.parent.relative_to(ROOT).as_posix()
        pitches.append(p)
    return pitches


def domain_key(p):
    d = p.get("domain", "")
    for i, name in enumerate(DOMAIN_ORDER):
        if name.split(" ")[0].lower() in d.lower():
            return i
    return len(DOMAIN_ORDER)


def main():
    pitches = load()
    out = [
        "# QUANTIX 2K26 project portfolio",
        "",
        "_Generated by `python tools/build_portfolio.py` from each project's `pitch.json`. Do not edit by hand._",
        "",
        f"{len(pitches)} working prototypes across all 6 hackathon domains. Every one runs offline with "
        "`python app.py` (Python 3.9+, standard library only) and ships with tests, a full `REPORT.md` "
        "and a generated pitch deck in `decks/`.",
        "",
        "| # | Project | Domain | Tagline | Port | Headline results |",
        "|---|---|---|---|---|---|",
    ]
    for p in sorted(pitches, key=lambda p: (domain_key(p), p["_dir"])):
        num = Path(p["_dir"]).name.split("-")[0]
        res = "; ".join(f"**{r['value']}** {r['label']}" for r in p.get("results", [])[:3])
        out.append(
            f"| {num} | [{p['name']}]({'../' + p['_dir']}/) | {p['domain']} | {p['tagline']} | "
            f"{p.get('port', '')} | {res} |"
        )
    out += ["", "## Per-project detail", ""]
    for p in pitches:
        d = "../" + p["_dir"]
        out += [
            f"### {p['name']} — {p['tagline']}",
            "",
            f"*{p['domain']}* · [code]({d}/) · [report]({d}/REPORT.md) · "
            f"[deck](../decks/{Path(p['_dir']).name}.pptx) · `cd {p['_dir']} && python app.py` → "
            f"http://localhost:{p.get('port', '')}",
            "",
            f"![{p['name']}]({d}/docs/screenshot.png)",
            "",
            "**Problem**",
            "",
            *[f"- {x}" for x in p.get("problem", [])],
            "",
            "**What it does**",
            "",
            *[f"- **{f['title']}** — {f['desc']}" for f in p.get("features", [])],
            "",
            "**Algorithms (all from scratch)**",
            "",
            *[f"- {a}" for a in p.get("algorithms", [])],
            "",
            "**Measured results**",
            "",
            *[f"- **{r['value']}** — {r['label']}" for r in p.get("results", [])],
            "",
        ]
    dest = ROOT / "docs" / "PORTFOLIO.md"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest.relative_to(ROOT)} ({len(pitches)} projects)")


if __name__ == "__main__":
    main()
